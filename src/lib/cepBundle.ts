// CEP (CAD Exchange Protocol) bundle: one zip with the STEP, the case, the field,
// the verification report, and a manifest of sha256 hashes.
//
// The manifest is the point. A bundle that cannot prove what it contains is just
// a folder — the hash list is what lets a downstream consumer verify that the
// `verdict` it reads belongs to the `wedge.step` it received. Every hash here is
// computed from the exact bytes written, in the same call, so they cannot drift
// from the archive.

import { buildZip, sha256Hex, type ZipEntry } from './zip';
import type { PipelineResult } from './phase1Pipeline';
import { inletMeshFor } from './inletSolve';
import { DEFAULT_INLET } from './inlet';
import { writeSu2Mesh } from './su2Mesh';
import { writeSu2Case, su2StatusNote } from './su2Case';
import { atmosphereAt } from './atmosphere';

export const CEP_VERSION = '1.0';

export interface ArtifactRecord {
  path: string;
  /** Bytes in the bundle. */
  bytes: number;
  sha256: string;
  mediaType: string;
  description: string;
}

export interface CepManifest {
  cep_version: string;
  /** Identifies what produced the bundle. Not a certificate. */
  generator: { name: string; version: string; method: string };
  created_utc: string;
  /** The verification claim, and its evidence, at the top level. */
  verification: {
    case: string;
    computed: Record<string, number>;
    exact: Record<string, number>;
    error_pct: Record<string, number>;
    criterion_pct: number;
    passed: boolean;
  };
  case_parameters: Record<string, number | string | boolean>;
  artifacts: ArtifactRecord[];
  /** sha256 of the bundle's own `manifest.json` cannot be included; see note. */
  manifest_note: string;
}

export interface CepBundle {
  zip: Uint8Array;
  manifest: CepManifest;
  /** sha256 of the finished archive, safe to publish. */
  bundleSha256: string;
  filename: string;
}

const encoder = new TextEncoder();

/** CSV of the computed field, for anyone who wants to re-plot it. */
function fieldCsv(r: PipelineResult): string {
  const { nx, ny, cx, cy } = r.solver.metrics;
  const P = r.solver.primitives;
  const rows = ['x_m,y_m,rho_kg_m3,u_m_s,v_m_s,p_pa,mach'];
  for (let j = 0; j < ny; j++) {
    for (let i = 0; i < nx; i++) {
      const s = i + 1 + (j + 1) * (nx + 2);
      const u = P.u[s];
      const v = P.v[s];
      const a = P.a[s];
      const mach = Math.hypot(u, v) / a;
      rows.push(
        [
          cx[i + j * nx].toFixed(6),
          cy[i + j * nx].toFixed(6),
          P.rho[s].toExponential(6),
          u.toFixed(3),
          v.toFixed(3),
          P.p[s].toFixed(3),
          mach.toFixed(5),
        ].join(','),
      );
    }
  }
  return rows.join('\n') + '\n';
}

/** The boundary conditions and numerical settings, as a machine-readable case. */
function caseJson(r: PipelineResult): string {
  return JSON.stringify(
    {
      schema: 'aeroforge.case.v1',
      geometry: {
        template: 'wedge',
        wedge_angle_deg: r.request.wedgeAngleDeg,
        chord_m: r.geometry.chordM,
        upstream_m: r.geometry.upstreamM,
        box_height_m: r.geometry.heightM,
        depth_m: 0.2,
      },
      freestream: {
        mach: r.request.mach,
        altitude_m: r.request.altitudeM,
        static_pressure_pa: r.flight.staticPressurePa,
        static_temperature_k: r.flight.staticTemperatureK,
        total_pressure_pa: r.flight.totalPressurePa,
        total_temperature_k: r.flight.totalTemperatureK,
        velocity_m_s: r.flight.velocity,
      },
      boundaries: {
        // SU2 marker names use lowercase underscores; these are the names the
        // bundled `.cfg` template refers to. See docs/phase-1-slice.md §4.
        inlet: 'freestream_left',
        outlet: 'supersonic_outlet',
        wall: 'wall',
        farfield: 'freestream_top',
      },
      numerics: {
        scheme: 'FV-MUSCL-minmod-HLLC',
        time_integration: 'explicit-euler-local-time-stepping',
        cfl: 1.2,
        order: 2,
        first_order_iterations: 1500,
        tolerance: 1e-5,
        grid: { nx: r.request.nx, ny: r.request.ny },
        iterations_run: r.solver.iterations,
        converged: r.solver.converged,
        final_residual: r.solver.residualHistory[r.solver.residualHistory.length - 1],
      },
    },
    null,
    2,
  );
}

/** A SU2-shaped config, so the same case can be re-run in a real solver later. */
function su2Cfg(r: PipelineResult): string {
  return `! Generated by AeroForge Phase 1. This is a case DEFINITION, not a
! solver input that has been tested against SU2 — the bundled solver is the
! TypeScript Euler code in src/lib/euler2d.ts. Marker names match case.json.
SOLVER= EULER
KIND_TURB_MODEL= NONE
MACH_NUMBER= ${r.request.mach}
FREESTREAM_PRESSURE= ${r.flight.staticPressurePa}
FREESTREAM_TEMPERATURE= ${r.flight.staticTemperatureK}
AOA= 0.0
SIDESLIP_ANGLE= 0.0
% Marker names must exist in the mesh before this cfg will run.
MARKER_FREESTREAM= ( freestream_left, freestream_top )
MARKER_SUPERSONIC_OUTLET= ( supersonic_outlet )
MARKER_EULER= ( wall )
MARKER_SYM= ( )
NUM_METHOD_GRAD= GREEN_GAUSS
CFL_NUMBER= ${1.2}
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_ERROR= 1E-6
LINEAR_SOLVER_ITER= 10
ITER= 16000
CONV_RESIDUAL_MINVAL= -5
MESH_FILENAME= wedge.su2
`;
}

export interface BundleInput {
  result: PipelineResult;
  /** Overridable for reproducible archives in tests. */
  createdUtc?: string;
}

/**
 * Assemble the CEP bundle.
 *
 * Async because hashing uses WebCrypto when available.
 */
export async function buildCepBundle(input: BundleInput): Promise<CepBundle> {
  const { result: r } = input;
  const createdUtc = input.createdUtc ?? new Date().toISOString();

  // Phase 3 sidecar inputs, built from the shared geometry helper.
  const su2MeshObj = inletMeshFor(DEFAULT_INLET, 120, 60);
  const su2Mesh = writeSu2Mesh(su2MeshObj);
  const su2Case = writeSu2Case({
    design: DEFAULT_INLET,
    atmosphere: atmosphereAt(DEFAULT_INLET.altitudeM),
    meshFilename: 'inlet.su2',
  });

  const files: { path: string; data: string; mediaType: string; description: string }[] = [
    {
      path: 'geometry/wedge.step',
      data: r.stepText,
      mediaType: 'application/step',
      description: 'Watertight ISO 10303-21 solid of the verified wedge',
    },
    {
      path: 'case/case.json',
      data: caseJson(r),
      mediaType: 'application/json',
      description: 'Geometry, freestream, boundary and numerical settings',
    },
    {
      path: 'case/wedge.cfg',
      data: su2Cfg(r),
      mediaType: 'text/plain',
      description: 'SU2-shaped case definition matching case.json (untested against SU2)',
    },
    {
      path: 'results/field.csv',
      data: fieldCsv(r),
      mediaType: 'text/csv',
      description: 'Cell-centred solution: x, y, rho, u, v, p, Mach',
    },
    {
      path: 'report/report.md',
      data: r.reportMarkdown,
      mediaType: 'text/markdown',
      description: 'Verification report with the verdict and its limits',
    },
    // ── Phase 3 sidecar inputs ───────────────────────────────────────────
    // The mesh and case are generated from the same geometry the browser
    // solver used, so a SU2 run would be comparable rather than merely similar.
    // They are UNRUN: SU2 is not available where these were produced (its
    // release binaries are served from a host this environment cannot reach).
    // The case file says so in its own header.
    {
      path: 'su2/inlet.su2',
      data: su2Mesh,
      mediaType: 'application/octet-stream',
      description: 'SU2 ASCII mesh of the Phase 2 inlet (markers: wall, far_top, inlet, outlet)',
    },
    {
      path: 'su2/inlet.cfg',
      data: su2Case,
      mediaType: 'text/plain',
      description: `SU2 v8.6 case for the inlet. ${su2StatusNote()}`,
    },
  ];

  // Hash the exact bytes that go into the archive.
  const artifacts: ArtifactRecord[] = [];
  for (const f of files) {
    const bytes = encoder.encode(f.data);
    artifacts.push({
      path: f.path,
      bytes: bytes.length,
      sha256: await sha256Hex(bytes),
      mediaType: f.mediaType,
      description: f.description,
    });
  }

  const manifest: CepManifest = {
    cep_version: CEP_VERSION,
    generator: {
      name: 'AeroForge',
      version: '0.2.0-phase1',
      method: 'src/lib/euler2d.ts (FV-MUSCL-HLLC), graded against src/lib/obliqueShock.ts',
    },
    created_utc: createdUtc,
    verification: {
      case: `wedge theta=${r.request.wedgeAngleDeg} deg, M=${r.request.mach}, alt=${r.request.altitudeM} m`,
      computed: {
        beta_deg: Number(r.extracted.betaDeg.toFixed(4)),
        pressure_ratio: Number(r.extracted.pressureRatio.toFixed(5)),
      },
      exact: {
        beta_deg: Number(r.exact.betaDeg.toFixed(4)),
        pressure_ratio: Number(r.exact.pressureRatio.toFixed(5)),
      },
      error_pct: {
        beta: Number(r.errors.betaPct.toFixed(3)),
        pressure_ratio: Number(r.errors.pressurePct.toFixed(3)),
      },
      criterion_pct: 2,
      passed: r.meetsExitCriterion,
    },
    case_parameters: {
      mach: r.request.mach,
      altitude_m: r.request.altitudeM,
      wedge_angle_deg: r.request.wedgeAngleDeg,
      material: r.request.materialId,
      grid: `${r.request.nx}x${r.request.ny}`,
      converged: r.solver.converged,
      iterations: r.solver.iterations,
    },
    artifacts,
    manifest_note:
      'manifest.json is not listed in its own artifact table: a file cannot contain ' +
      'its own hash. Integrity of the manifest itself is covered by bundle_sha256, ' +
      'which the caller should publish separately from the archive.',
  };

  const manifestText = JSON.stringify(manifest, null, 2);
  const entries: ZipEntry[] = [
    { name: 'manifest.json', data: manifestText },
    ...files.map((f) => ({ name: f.path, data: f.data })),
  ];

  const zip = buildZip(entries);
  const bundleSha256 = await sha256Hex(zip);

  const angle = String(r.request.wedgeAngleDeg).replace('.', 'p');
  const mach = String(r.request.mach).replace('.', 'p');
  return {
    zip,
    manifest,
    bundleSha256,
    filename: `aeroforge_cep_wedge_t${angle}_M${mach}.zip`,
  };
}

/** A short human-readable summary of the manifest, for the UI. */
export function describeBundle(b: CepBundle): string {
  const n = b.manifest.artifacts.length;
  const kb = (b.zip.length / 1024).toFixed(1);
  return `${n} files · ${kb} kB · sha256 ${b.bundleSha256.slice(0, 12)}…`;
}
